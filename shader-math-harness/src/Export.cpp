std::string BuildSollyaScript(const Contract& contract)
{
    std::ostringstream script;
    script << "// Generated by Metallic ShaderMathHarness. Contract: " << contract.id << "\n";
    script << "// Purpose: certified supremum norm of the approximation error of the\n";
    script << "// exact-rational polynomial against exp(-x) on [0; 1/4].\n";
    script << "// Run with: sollya " << contract.id << ".sollya\n";
    script << "prec = 512;\n";
    script << "f = exp(-x);\n";
    script << "p = 1 + x * (-1 + x * (1/2 + x * (-1/6 + x * (1/24))));\n";
    script << "b = supnorm(p, f, [0; 1/4], absolute, symmetric);\n";
    script << "print(\"=SUPNORM=\", b);\n";
    script << "quit;\n";
    return script.str();
}

std::string BuildGappaScript(const Contract& contract, const CandidateModel& model)
{
    std::ostringstream script;
    script << "# Generated by Metallic ShaderMathHarness. Contract: " << contract.id << "\n";
    script << "# Claim (host-proved internally): |y - p| stays below the gamma bound for\n";
    script << "# every binary32 x in [0, 0.25], where p is the exact-real polynomial with\n";
    script << "# the same quantized coefficients and y follows four single-rounding FMA steps.\n";
    script << "# NOTE: template. The script was generated without Gappa installed; validate\n";
    script << "# the syntax against your Gappa version before trusting results.\n\n";

    script << "x float32 <- [0, 0.25];\n\n";
    for (std::size_t k = 0; k < model.coefficientBits.size(); ++k)
    {
        script << "c" << k << " = " << GappaLiteral(model.coefficientBits[k]) << ";\n";
    }
    script << "\nh1 = float32<ne>(c4 * x + c3);\n";
    script << "h2 = float32<ne>(h1 * x + c2);\n";
    script << "h3 = float32<ne>(h2 * x + c1);\n";
    script << "y  = float32<ne>(h3 * x + c0);\n\n";
    script << "p = c0 + x * (c1 + x * (c2 + x * (c3 + x * c4)));\n\n";
    script << "{ |y - p| <= 3.1e-7 }\n";
    return script.str();
}

std::string BuildSlangModule(const Contract& contract, const CandidateModel& model)
{
    std::ostringstream shader;
    shader << "// Generated by Metallic ShaderMathHarness - DO NOT EDIT BY HAND.\n";
    shader << "// Contract: " << contract.id << " (content hash " << contract.sourceHash << ")\n";
    shader << "// Model: " << DescribeProofModel(contract) << "\n";
    shader << "// The certificate covers THIS operation graph under the proof model only.\n";
    shader << "// GPU compilation may split, fuse, or reassociate the operations: compare\n";
    shader << "// compiled GPU outputs against the emitted manifest before trusting them.\n\n";
    shader << "module AttenuationExpSmallTauV1;\n\n";
    shader << "export float AttenuationExpSmallTau(float tau)\n";
    shader << "{\n";
    for (std::size_t k = 0; k < model.coefficientBits.size(); ++k)
    {
        shader << "    float c" << k << " = bitcast<float>(" << BitString(model.coefficientBits[k])
               << "u);\n";
    }
    shader << "\n";
    shader << "    float h = fma(c4, tau, c3);\n";
    shader << "    h = fma(h, tau, c2);\n";
    shader << "    h = fma(h, tau, c1);\n";
    shader << "    float y = fma(h, tau, c0);\n";
    if (model.clamp01)
    {
        shader << "    return clamp(y, 0.0, 1.0);\n";
    }
    else
    {
        shader << "    return y;\n";
    }
    shader << "}\n";
    return shader.str();
}

std::string BuildManifestEntriesText(const Contract& contract, const CandidateModel& model,
    const SweepResults& sweep, std::uint32_t randomEntryCount, std::uint32_t worstEntryCount)
{
    std::vector<std::uint32_t> inputs;

    const std::uint32_t gridLo = sweep.gridLoBits;
    const std::uint32_t gridHi = sweep.gridHiBits;
    auto push = [&inputs, gridLo, gridHi](std::uint32_t bits)
    {
        if (bits >= gridLo && bits <= gridHi)
        {
            inputs.push_back(bits);
        }
    };

    for (std::size_t i = 0;
         i < sweep.worst.size() && i < static_cast<std::size_t>(worstEntryCount); ++i)
    {
        push(sweep.worst[i].inBits);
    }
    push(gridLo);
    push(gridLo + 1);
    push(0x00000001);
    push(0x007FFFFF);
    push(0x007FFFFE);
    push(0x00800000);
    push(0x00800001);
    for (int exponent = -125; exponent <= -3; ++exponent)
    {
        const std::uint32_t base = static_cast<std::uint32_t>((exponent + 127) << 23);
        push(base - 1);
        push(base);
        push(base + 1);
    }
    if (gridHi >= 1)
    {
        push(gridHi - 1);
    }
    push(gridHi);

    std::uint64_t state = Fnv1a64(contract.id) ^ 0x9E3779B97F4A7C15ULL;
    for (std::uint32_t i = 0; i < randomEntryCount; ++i)
    {
        const std::uint64_t value = Xorshift64(state);
        push(static_cast<std::uint32_t>(gridLo + value % (gridHi - gridLo + 1)));
    }

    std::ostringstream text;
    for (const std::uint32_t bits : inputs)
    {
        const float y = EvaluateModelF32(model, FloatFromBits(bits));
        text << BitString(bits) << " " << BitString(BitsFromFloat(y)) << "\n";
    }
    return text.str();
}

ExportArtifacts WriteExports(const Contract& contract, const CandidateModel& model,
    const SweepResults& sweep, const std::string& outDirectory, const ExportOptions& options)
{
    namespace fs = std::filesystem;
    ExportArtifacts artifacts;
    artifacts.outDirectory = outDirectory;
    fs::create_directories(fs::path(outDirectory) / "exports");

    const std::string sollyaText = BuildSollyaScript(contract);
    artifacts.sollya.path = (fs::path(outDirectory) / "exports" / (contract.id + ".sollya")).string();
    artifacts.sollya.contentHash = HashToHex(Fnv1a64(sollyaText));
    WriteTextFile(artifacts.sollya.path, sollyaText);
    artifacts.sollya.note = "script written; supnorm(p, exp(-x), [0;1/4], absolute, symmetric)";
    if (options.attemptSollya)
    {
        const std::string output =
            CaptureCommand("sollya \"" + artifacts.sollya.path + "\" 2>&1");
        if (output.empty())
        {
            artifacts.sollya.note = "sollya was invoked but produced no usable output";
        }
        else
        {
            artifacts.sollya.executed = true;
            artifacts.sollya.toolOutput = output;
        }
    }
    else
    {
        artifacts.sollya.note += "; tool not invoked (pass --run-sollya with Sollya on PATH)";
    }

    const std::string gappaText = BuildGappaScript(contract, model);
    artifacts.gappa.path = (fs::path(outDirectory) / "exports" / (contract.id + ".gappa")).string();
    artifacts.gappa.contentHash = HashToHex(Fnv1a64(gappaText));
    WriteTextFile(artifacts.gappa.path, gappaText);
    artifacts.gappa.note = "template written; syntax unvalidated (Gappa not installed here)";
    if (options.attemptGappa)
    {
        const std::string output =
            CaptureCommand("gappa \"" + artifacts.gappa.path + "\" 2>&1");
        if (output.empty())
        {
            artifacts.gappa.note = "gappa was invoked but produced no usable output";
        }
        else
        {
            artifacts.gappa.executed = true;
            artifacts.gappa.toolOutput = output;
        }
    }

    const std::string slangText = BuildSlangModule(contract, model);
    artifacts.slang.path = (fs::path(outDirectory) / "exports" / "AttenuationExpSmallTauV1.slang").string();
    artifacts.slang.contentHash = HashToHex(Fnv1a64(slangText));
    WriteTextFile(artifacts.slang.path, slangText);
    artifacts.slang.note = "generated from the same candidate graph; compile validation pending";

    const std::string entries = BuildManifestEntriesText(contract, model, sweep,
        options.randomEntryCount, options.worstEntryCount);
    artifacts.manifestPath = (fs::path(outDirectory) / "exports" / "gpu-manifest.txt").string();
    artifacts.manifestHash = HashToHex(Fnv1a64(entries));
    artifacts.manifestEntryCount = static_cast<std::uint64_t>(
        std::count(entries.begin(), entries.end(), '\n'));
    std::ostringstream manifest;
    manifest << "# Generated by Metallic ShaderMathHarness\n";
    manifest << "# contract " << contract.id << " hash " << contract.sourceHash << "\n";
    manifest << "# model " << DescribeProofModel(contract) << "\n";
    manifest << "# format: <input bits> <expected model output bits>\n";
    manifest << entries;
    WriteTextFile(artifacts.manifestPath, manifest.str());

    return artifacts;
}

