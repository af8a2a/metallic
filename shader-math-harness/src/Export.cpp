std::string ReadFileOrEmpty(const std::string& path)
{
    std::ifstream stream(path, std::ios::binary);
    if (!stream)
    {
        return std::string();
    }
    std::ostringstream content;
    content << stream.rdbuf();
    return content.str();
}

bool WriteTextFile(const std::string& path, const std::string& content)
{
    std::ofstream stream(path, std::ios::binary);
    if (!stream)
    {
        return false;
    }
    stream.write(content.data(), static_cast<std::streamsize>(content.size()));
    return static_cast<bool>(stream);
}

std::string CaptureCommand(const std::string& command)
{
    std::FILE* pipe = OpenPipe(command.c_str());
    if (pipe == nullptr)
    {
        return std::string();
    }
    std::ostringstream output;
    char buffer[4096];
    while (std::fgets(buffer, static_cast<int>(sizeof(buffer)), pipe) != nullptr)
    {
        output << buffer;
    }
    const int code = ClosePipe(pipe);
    if (code != 0)
    {
        return std::string();
    }
    return output.str();
}

std::string BitString(std::uint32_t bits)
{
    static const char* kDigits = "0123456789abcdef";
    std::string text = "0x00000000";
    for (int i = 7; i >= 0; --i)
    {
        text[static_cast<std::size_t>(9 - i)] = kDigits[(bits >> (i * 4)) & 0xF];
    }
    return text;
}

// Exact dyadic literal (m * 2^e) in Gappa syntax for a binary32 bit pattern.
std::string GappaLiteral(std::uint32_t bits)
{
    const std::uint32_t mantissa = bits & 0x007FFFFFu;
    const std::int32_t biased = static_cast<std::int32_t>((bits >> 23) & 0xFFu);
    const bool negative = (bits & 0x80000000u) != 0;
    std::int64_t integerMantissa = 0;
    std::int32_t exponent = 0;
    if (biased == 0)
    {
        integerMantissa = mantissa;
        exponent = -149;
    }
    else
    {
        integerMantissa = static_cast<std::int64_t>(mantissa) | (1LL << 23);
        exponent = biased - 127 - 23;
    }
    std::ostringstream out;
    out << (negative ? "-" : "") << integerMantissa;
    if (exponent != 0)
    {
        out << " * 1b" << exponent;
    }
    return out.str();
}

std::uint64_t Xorshift64(std::uint64_t& state)
{
    state ^= state << 13;
    state ^= state >> 7;
    state ^= state << 17;
    return state;
}

